# Import os to read environment variables.
import os

# Import typing helpers for structured data.
from typing import Dict, Any, List

# Import the Tavily client for web searches.
from tavily import TavilyClient

# Import the shared research state.
from backend.graph.state import ResearchState

# Import load_dotenv to load configuration from .env.
from dotenv import load_dotenv


# Load environment variables from the project root.
load_dotenv()


def researcher_agent(
    state: ResearchState,
) -> Dict[str, Any]:
    """
    Research the coordinator's tasks using Tavily.

    The agent searches for the original question and
    each research task, then combines duplicate-free
    search results into a structured evidence collection.
    """

    # Stop if the coordinator or an earlier stage failed.
    if state.get("status") == "failed":
        return {}

    # Read the original research question.
    question = state.get("research_question", "").strip()

    # Read the research plan generated by the coordinator.
    research_plan = state.get("research_plan", [])

    # Read the Tavily API key from the environment.
    api_key = os.getenv("TAVILY_API_KEY")

    # Check that the API key is configured.
    if not api_key or "PASTE_YOUR" in api_key:
        return {
            "search_results": [],
            "status": "failed",
            "error": (
                "TAVILY_API_KEY is missing or invalid. "
                "Check your project's .env file."
            ),
            "activity_log": [
                "Researcher Agent could not start: Tavily API key unavailable."
            ],
        }

    # Check that a research question was provided.
    if not question:
        return {
            "search_results": [],
            "status": "failed",
            "error": "A research question is required.",
            "activity_log": [
                "Researcher Agent stopped because the question was empty."
            ],
        }

    # Create the list of queries that will be searched.
    queries: List[str] = [question]

    # Add the coordinator's individual research tasks.
    for task in research_plan:
        cleaned_task = task.strip()

        # Avoid adding empty tasks or repeating the main question.
        if cleaned_task and cleaned_task.lower() != question.lower():
            queries.append(cleaned_task)

    # Remove duplicate queries while preserving their order.
    unique_queries = list(dict.fromkeys(queries))

    # Limit the number of searches to control API usage.
    # The original question plus up to four plan tasks are used.
    unique_queries = unique_queries[:5]

    # Keep results indexed by URL to remove duplicates.
    collected_results: Dict[str, Dict[str, Any]] = {}

    # Record which queries have been searched.
    searched_queries: List[str] = []

    try:
        # Create the Tavily search client.
        client = TavilyClient(api_key=api_key)

        # Search each selected research query.
        for query in unique_queries:

            # Record the query for reporting and debugging.
            searched_queries.append(query)

            # Search for up to three results per query.
            response = client.search(
                query=query,
                max_results=3,
            )

            # Extract the results returned by Tavily.
            results = response.get("results", [])

            # Process each returned source.
            for result in results:

                # Extract the source URL.
                url = result.get("url", "").strip()

                # Ignore results that do not contain a URL.
                if not url:
                    continue

                # Store each unique source only once.
                if url not in collected_results:
                    collected_results[url] = {
                        "title": result.get(
                            "title",
                            "Untitled",
                        ),
                        "url": url,
                        "content": result.get(
                            "content",
                            "",
                        ),
                        "query": query,
                    }

        # Convert the unique results into a list.
        search_results = list(collected_results.values())

        # Stop if no usable sources were collected.
        if not search_results:
            return {
                "search_results": [],
                "status": "failed",
                "error": (
                    "The Researcher Agent could not find "
                    "any usable web sources."
                ),
                "activity_log": [
                    "Researcher Agent completed searches without usable sources."
                ],
            }

        # Return the research evidence to the shared state.
        return {
            "search_results": search_results,
            "status": "analyzing",
            "error": "",
            "activity_log": [
                (
                    "Researcher Agent searched "
                    f"{len(searched_queries)} queries."
                ),
                (
                    "Researcher Agent collected "
                    f"{len(search_results)} unique sources."
                ),
            ],
        }

    except Exception as error:
        # Report the error without exposing the API key.
        return {
            "search_results": [],
            "status": "failed",
            "error": (
                "Researcher Agent failed: "
                f"{type(error).__name__}: {error}"
            ),
            "activity_log": [
                "Researcher Agent encountered a search error."
            ],
        }