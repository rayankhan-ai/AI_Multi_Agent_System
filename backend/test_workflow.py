# Import os to read environment variables.
import os

# Import load_dotenv to load the project's configuration.
from dotenv import load_dotenv

# Import the complete research workflow.
from backend.graph.workflow import run_research


# Load environment variables from the project's .env file.
load_dotenv()


def main():
    """Run and display the multi-agent research workflow."""

    # Ask the user for a research question.
    question = input(
        "Enter a research question: "
    ).strip()

    # Reject an empty question.
    if not question:
        print("ERROR: Please enter a research question.")
        return

    # Verify that the Tavily API key exists.
    if not os.getenv("TAVILY_API_KEY"):
        print("ERROR: TAVILY_API_KEY is missing from .env.")
        return

    # Verify that the Groq API key exists.
    if not os.getenv("GROQ_API_KEY"):
        print("ERROR: GROQ_API_KEY is missing from .env.")
        return

    print("\nStarting the multi-agent research workflow...\n")

    try:
        # Run the complete research workflow.
        result = run_research(question)

        # Display the workflow status.
        print("\n" + "=" * 65)
        print("WORKFLOW STATUS")
        print("=" * 65)

        print(result.get("status", "unknown"))

        # Display any workflow error.
        if result.get("error"):
            print("\nERROR:")
            print(result["error"])

        # Display the Coordinator Agent's plan.
        print("\n" + "=" * 65)
        print("COORDINATOR RESEARCH PLAN")
        print("=" * 65)

        plan = result.get("research_plan", [])

        for index, task in enumerate(plan, start=1):
            print(f"{index}. {task}")

        # Display the workflow activity log.
        print("\n" + "=" * 65)
        print("ACTIVITY LOG")
        print("=" * 65)

        for activity in result.get("activity_log", []):
            print(f"- {activity}")

        # Display the sources collected by the Researcher Agent.
        print("\n" + "=" * 65)
        print("RESEARCH SOURCES")
        print("=" * 65)

        sources = result.get("search_results", [])

        for index, source in enumerate(sources, start=1):
            print(f"\nSource {index}")
            print("Title:", source.get("title", ""))
            print("URL:", source.get("url", ""))
            print("Search query:", source.get("query", ""))

        # Display the Analyst Agent's answer.
        print("\n" + "=" * 65)
        print("ANALYST ANSWER")
        print("=" * 65)

        print(
            result.get(
                "analysis",
                "No analysis was generated.",
            )
        )

        # Display the Fact-Checker Agent's verification report.
        print("\n" + "=" * 65)
        print("FACT-CHECKING REPORT")
        print("=" * 65)

        fact_check = result.get("fact_check", "")

        if fact_check:
            print(fact_check)
        else:
            print("No fact-checking report was generated.")

        # Print the final report generated by the Report Writer Agent.
        print("\n" + "=" * 70)
        print("FINAL RESEARCH REPORT")
        print("=" * 70)

        print(
        result.get(
            "final_report",
            "No final report was generated.",
        )
        )
        
        # Display the saved report location when available.
        report_file = result.get("report_file", "")

        if report_file:
            print("\n" + "=" * 70)
            print("SAVED REPORT")
            print("=" * 70)

            print("Report filename:", result.get("report_filename"))
            print("Report location:", report_file)
        else:
            print("\nNo saved report path was returned.")

        # Explain the result of the workflow.
        print("\n" + "=" * 65)

        if result.get("status") == "completed":
            print("SUCCESS: Research and fact-checking completed.")
        else:
            print("The workflow did not complete successfully.")

        print("=" * 65)

    except Exception as error:
        # Display unexpected errors without exposing API credentials.
        print("\nAn unexpected error occurred.")
        print(f"Error type: {type(error).__name__}")
        print(f"Details: {error}")


# Execute the test when this file is run directly.
if __name__ == "__main__":
    main()